from __future__ import annotations

import json
from dataclasses import dataclass
from typing import Any, Protocol

from pydantic import ValidationError

from .models import Plan, Risk, ToolCall


class Planner(Protocol):
    async def plan(self, goal: str, context: dict[str, Any]) -> Plan: ...


@dataclass(frozen=True)
class RulePlanner:
    """Deterministic fallback planner used when no model is configured."""

    async def plan(self, goal: str, context: dict[str, Any]) -> Plan:
        text = goal.lower()
        steps: list[ToolCall] = []
        if any(word in text for word in ("search", "find", "look up", "check")):
            steps.append(ToolCall(name="web.search", arguments={"query": goal}, risk=Risk.READ))
        if any(word in text for word in ("send", "post", "message", "email")):
            steps.append(ToolCall(name="communications.send", arguments={"text": goal}, risk=Risk.HIGH))
        if any(word in text for word in ("buy", "purchase", "order", "pay")):
            steps.append(ToolCall(name="commerce.purchase", arguments={"request": goal}, risk=Risk.CRITICAL))
        return Plan(goal=goal, steps=steps, explanation="Generated by the deterministic fallback planner.")


@dataclass
class ModelPlanner:
    """Uses an LLM to emit only structured Plan JSON, then validates every tool call."""

    llm: Any
    fallback: Planner

    async def plan(self, goal: str, context: dict[str, Any]) -> Plan:
        tools = context.get("available_tools", [])
        memory = context.get("memory", [])[-12:]
        messages = [
            {
                "role": "system",
                "content": (
                    "You are TOM's planning engine. Return ONLY valid JSON matching "
                    '{"goal": string, "steps": [{"name": string, "arguments": object, "risk": "read|low|high|critical"}], "explanation": string}. '
                    "Use only tools listed in available_tools. Never invent a tool. "
                    "Sending messages, purchases, deletion, account/security changes are high or critical. "
                    "Do not execute anything; only create the plan."
                ),
            },
            {
                "role": "user",
                "content": json.dumps(
                    {"goal": goal, "available_tools": tools, "recent_memory": memory, "context": context},
                    ensure_ascii=False,
                ),
            },
        ]
        try:
            raw = await self.llm.complete(messages, temperature=0, response_format={"type": "json_object"})
            return self._parse(raw, goal, tools)
        except (ValueError, TypeError, KeyError, ValidationError, json.JSONDecodeError):
            return await self.fallback.plan(goal, context)

    @staticmethod
    def _parse(raw: str, goal: str, tools: list[dict[str, Any]]) -> Plan:
        text = raw.strip()
        if text.startswith("```"):
            text = text.strip("`").replace("json\n", "", 1).strip()
        payload = json.loads(text)
        plan = Plan.model_validate(payload)
        allowed = {item.get("name") for item in tools}
        if allowed and any(step.name not in allowed for step in plan.steps):
            raise ValueError("model returned an unavailable tool")
        return plan.model_copy(update={"goal": goal})
